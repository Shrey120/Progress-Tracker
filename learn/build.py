#!/usr/bin/env python3
"""Compile content/**/*.md into content.js, and check every reference solution.

    python3 build.py           build content.js
    python3 build.py --verify  build, then run each solution against its tests
                               (and confirm each starter does NOT already pass)

Lesson file format
------------------
    ---
    course: python
    module: basics
    title: Python basics
    order: 1
    ---
    === lesson: variables | Variables and types
    markdown...

    ::: exercise swap | Swap two values
    prompt markdown
    --- starter
    code
    --- tests
    assert swap(1, 2) == (2, 1)      <- one test per line
    --- solution
    code
    --- hint
    markdown (repeatable)
    :::
"""
import ast, io, json, re, sys, glob, os, contextlib, signal

ROOT = os.path.dirname(os.path.abspath(__file__))


def parse_file(path):
    text = open(path, encoding="utf-8").read()
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not m:
        raise SystemExit(f"{path}: missing front matter")
    meta = dict(line.split(":", 1) for line in m.group(1).splitlines() if ":" in line)
    meta = {k.strip(): v.strip() for k, v in meta.items()}
    body = text[m.end():]
    lessons = []
    for chunk in re.split(r"^=== lesson: ", body, flags=re.M)[1:]:
        header, _, rest = chunk.partition("\n")
        lid, _, title = header.partition("|")
        md_parts, exercises = [], []
        pos = 0
        for em in re.finditer(r"^::: exercise (.+?)\n(.*?)^:::\s*$", rest, flags=re.M | re.S):
            md_parts.append(rest[pos:em.start()])
            pos = em.end()
            exercises.append(parse_exercise(path, em.group(1), em.group(2)))
        md_parts.append(rest[pos:])
        lessons.append({"id": lid.strip(), "title": title.strip(), "md": "".join(md_parts).strip(), "exercises": exercises})
    return meta, lessons


def parse_exercise(path, header, body):
    eid, _, title = header.partition("|")
    parts = re.split(r"^--- (starter|tests|solution|hint|stdin)\s*$\n?", body, flags=re.M)
    ex = {"id": eid.strip(), "title": title.strip(), "prompt": parts[0].strip(), "starter": "", "tests": [], "solution": "", "hints": []}
    for name, content in zip(parts[1::2], parts[2::2]):
        content = content.rstrip("\n")
        if name == "tests":
            for line in content.splitlines():
                if line.strip() and not line.strip().startswith("#"):
                    label = re.sub(r"^assert\s+", "", line.strip())
                    ex["tests"].append({"label": label, "code": line.strip()})
        elif name == "hint":
            ex["hints"].append(content.strip())
        elif name == "stdin":
            ex["stdin"] = content + "\n"
        else:
            ex[name] = content + "\n"
    if not ex["tests"]:
        raise SystemExit(f"{path}: exercise {eid} has no tests")
    return ex


def build():
    courses = json.load(open(os.path.join(ROOT, "content", "courses.json"), encoding="utf-8"))
    by_id = {c["id"]: c for c in courses}
    for c in courses:
        c.setdefault("modules", [])
    files = sorted(glob.glob(os.path.join(ROOT, "content", "**", "*.md"), recursive=True))
    loaded = []
    for f in files:
        meta, lessons = parse_file(f)
        loaded.append((int(meta.get("order", 999)), meta, lessons))
    for _, meta, lessons in sorted(loaded, key=lambda x: x[0]):
        course = by_id[meta["course"]]
        existing = next((m for m in course["modules"] if m["id"] == meta["module"]), None)
        if existing:  # a planned module (from courses.json) gets its written lessons swapped in
            written = {l["id"]: l for l in lessons}
            planned_ids = {l["id"] for l in existing["lessons"]}
            # written lessons keep the order they were written in (basics first); planned-only ones follow
            planned = {l["id"]: l for l in existing["lessons"]}
            existing["lessons"] = [{**planned.get(l["id"], {}), **l} for l in lessons] + [l for l in existing["lessons"] if l["id"] not in written]
            for k in ("icon", "tagline", "level"):
                if meta.get(k):
                    existing[k] = meta[k]
        else:
            course["modules"].append({"id": meta["module"], "title": meta["title"], "level": meta.get("level", ""),
                                      "icon": meta.get("icon", ""), "tagline": meta.get("tagline", ""), "lessons": lessons})
    for c in courses:
        for m in c["modules"]:
            ids = [l["id"] for l in m["lessons"]]
            if len(ids) != len(set(ids)):
                raise SystemExit(f"duplicate lesson id in {c['id']}/{m['id']}")
    out = "/* generated by build.py — edit content/ instead */\nwindow.COURSES = " + json.dumps(courses, ensure_ascii=False, separators=(",", ":")) + ";\n"
    open(os.path.join(ROOT, "content.js"), "w", encoding="utf-8").write(out)
    return courses


# ---- verification: same semantics as runner-worker.js ----
def exec_test(code, g):
    tree = ast.parse(code)
    node = tree.body[0] if len(tree.body) == 1 else None
    if (isinstance(node, ast.Assert) and node.msg is None and isinstance(node.test, ast.Compare)
            and len(node.test.ops) == 1 and isinstance(node.test.ops[0], ast.Eq)):
        got = eval(compile(ast.Expression(node.test.left), "test", "eval"), g)
        exp = eval(compile(ast.Expression(node.test.comparators[0]), "test", "eval"), g)
        if got != exp:
            raise AssertionError("expected " + repr(exp) + ", got " + repr(got))
    else:
        exec(compile(tree, "test", "exec"), g)


class Timeout(Exception):
    pass


def run(code, tests, stdin):
    g = {"__name__": "__main__"}
    old_in = sys.stdin
    sys.stdin = io.StringIO(stdin or "")
    signal.signal(signal.SIGALRM, lambda *a: (_ for _ in ()).throw(Timeout()))
    signal.alarm(5)
    try:
        with contextlib.redirect_stdout(io.StringIO()):
            try:
                exec(compile(code, "solution.py", "exec"), g)
            except Exception as e:
                return None, f"{type(e).__name__}: {e}"
            results = []
            for t in tests:
                try:
                    exec_test(t["code"], g)
                    results.append((t["label"], True, ""))
                except Exception as e:
                    results.append((t["label"], False, f"{type(e).__name__}: {e}"))
            return results, None
    except Timeout:
        return None, "timeout"
    finally:
        signal.alarm(0)
        sys.stdin = old_in


def verify(courses):
    bad = 0; n = 0
    for c in courses:
        for m in c["modules"]:
            for l in m["lessons"]:
                for e in l.get("exercises", []):
                    n += 1
                    where = f"{c['id']}/{m['id']}/{l['id']}/{e['id']}"
                    res, err = run(e["solution"], e["tests"], e.get("stdin"))
                    if err or not all(ok for _, ok, _ in res):
                        bad += 1
                        print(f"FAIL solution {where}: {err or [r for r in res if not r[1]]}")
                    sres, serr = run(e["starter"], e["tests"], e.get("stdin"))
                    if not serr and sres and all(ok for _, ok, _ in sres):
                        bad += 1
                        print(f"STARTER ALREADY PASSES {where}")
    print(f"{n} exercises checked, {bad} problems")
    return bad == 0


SQL_ERRORS_OK = {"transactions-acid"}  # lessons that show a failing statement on purpose


def verify_snippets(courses):
    """Run every ```jsrun block with node and every ```pyrun block with python; report failures."""
    import subprocess, tempfile
    bad = 0; n = 0
    runner = (
        "const AsyncFunction = Object.getPrototypeOf(async function () {}).constructor;"
        "const code = require('fs').readFileSync(process.argv[1], 'utf8');"
        "process.on('unhandledRejection', e => { console.log('UNHANDLED', e && e.message); process.exitCode = 3; });"
        "new AsyncFunction(code)().then(() => setTimeout(() => {}, 400), e => { console.log('ERROR', e && e.message); process.exitCode = 2; });"
    )
    for c in courses:
        for m in c["modules"]:
            for l in m["lessons"]:
                for lang, src in re.findall(r"```(jsrun|pyrun|sqlrun)\n(.*?)\n```", l.get("md", ""), flags=re.S):
                    n += 1
                    if lang == "sqlrun":
                        import sqlite3
                        db = sqlite3.connect(":memory:")
                        db.executescript(open(os.path.join(ROOT, "sql-seed.sql")).read())
                        try:
                            db.executescript(src)
                        except Exception as e:
                            if l["id"] not in SQL_ERRORS_OK:
                                bad += 1
                                print(f"SNIPPET sql {c['id']}/{m['id']}/{l['id']}: {e}")
                        db.close()
                        continue
                    with tempfile.NamedTemporaryFile("w", suffix=".txt", delete=False) as f:
                        f.write(src)
                    cmd = ["node", "-e", runner, f.name] if lang == "jsrun" else [sys.executable, "-I", f.name]
                    try:
                        r = subprocess.run(cmd, capture_output=True, text=True, timeout=10)
                        failed = r.returncode != 0
                        why = (r.stdout + r.stderr).strip().splitlines()[-1:] if failed else ""
                    except subprocess.TimeoutExpired:
                        failed, why = True, ["timeout"]
                    if failed and not l["id"] in ("reading-errors",):
                        bad += 1
                        print(f"SNIPPET {lang} {c['id']}/{m['id']}/{l['id']}: {why}")
    print(f"{n} runnable snippets checked, {bad} problems")
    return bad == 0


if __name__ == "__main__":
    sys.setrecursionlimit(10000)
    courses = build()
    for c in courses:
        total = sum(len(m["lessons"]) for m in c["modules"])
        done = sum(1 for m in c["modules"] for l in m["lessons"] if l.get("md"))
        print(f"{c['id']}: {done}/{total} lessons written, {len(c['modules'])} topics")
    if "--verify" in sys.argv:
        ok = verify(courses)
        ok = verify_snippets(courses) and ok
        sys.exit(0 if ok else 1)
